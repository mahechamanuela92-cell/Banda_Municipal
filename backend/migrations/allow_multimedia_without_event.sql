DO $$
BEGIN
	IF EXISTS (
		SELECT 1 FROM information_schema.columns
		WHERE table_schema = 'public'
			AND table_name = 'multimedia'
			AND column_name = 'id'
	) AND NOT EXISTS (
		SELECT 1 FROM information_schema.columns
		WHERE table_schema = 'public'
			AND table_name = 'multimedia'
			AND column_name = 'id_multimedia'
	) THEN
		ALTER TABLE public.multimedia RENAME COLUMN id TO id_multimedia;
	END IF;
END
$$;

ALTER TABLE public.multimedia
	ADD COLUMN IF NOT EXISTS id_multimedia BIGINT GENERATED BY DEFAULT AS IDENTITY,
	ADD COLUMN IF NOT EXISTS user_id UUID,
	ADD COLUMN IF NOT EXISTS id_evento BIGINT,
	ADD COLUMN IF NOT EXISTS titulo TEXT,
	ADD COLUMN IF NOT EXISTS tipo_archivo TEXT,
	ADD COLUMN IF NOT EXISTS url_archivo TEXT,
	ADD COLUMN IF NOT EXISTS fecha_subida TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	ADD COLUMN IF NOT EXISTS foto TEXT,
	ADD COLUMN IF NOT EXISTS video TEXT;

ALTER TABLE public.multimedia
	ALTER COLUMN id_evento DROP NOT NULL;

UPDATE public.multimedia
SET url_archivo = COALESCE(NULLIF(url_archivo, ''), NULLIF(foto, ''), NULLIF(video, '')),
		tipo_archivo = COALESCE(
			NULLIF(tipo_archivo, ''),
			CASE
				WHEN NULLIF(foto, '') IS NOT NULL THEN 'foto'
				WHEN NULLIF(video, '') IS NOT NULL THEN 'video'
			END
		)
WHERE url_archivo IS NULL OR tipo_archivo IS NULL;

DO $$
BEGIN
	IF NOT EXISTS (
		SELECT 1 FROM pg_constraint
		WHERE conrelid = 'public.multimedia'::regclass
			AND contype = 'p'
	) THEN
		ALTER TABLE public.multimedia
			ADD CONSTRAINT multimedia_pkey PRIMARY KEY (id_multimedia);
	END IF;

	IF NOT EXISTS (
		SELECT 1 FROM pg_constraint
		WHERE conrelid = 'public.multimedia'::regclass
			AND conname = 'multimedia_tipo_archivo_check'
	) THEN
		ALTER TABLE public.multimedia
			ADD CONSTRAINT multimedia_tipo_archivo_check
			CHECK (tipo_archivo IN ('foto', 'video'));
	END IF;
END
$$;